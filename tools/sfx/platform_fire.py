"""Build C19 first-person shots from generated attack layers and the CC0 weapon recordings."""

import argparse
import json
from pathlib import Path
import sys

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from build_sfx import encode_pack
import common as C

PACK = 'platform_fire'
PLATFORMS = {
    'rifle': ('rifle', 'ak', 'battle', 'famas'),
    'smg': ('smg', 'mp7', 'smg45', 'vector'),
    'pistol': ('pistol', 'glock', 'pistol45', 'pistol50'),
    'shotgun': ('shotgun', 'aa12'),
    'dmr': ('dmr',),
    'sniper': ('sniper',),
    'heavy': ('sniper50',),
}
CREDITS = C.ROOT / 'assets/sfx/credits.json'


def rms(samples):
    return np.sqrt(np.mean(samples ** 2))


def attack(samples):
    # A short layer adds a new attack. Keep the profile's recorded action and decay.
    samples = C.ff(samples, 'highpass=f=55,lowpass=f=14000')
    samples = C.trim(samples, -21, pre=0.002)[:round(C.SR * 0.085)]
    samples = C.fade(samples, fin=0.001, fout=0.035)
    return C.norm_rms(samples, -18, -3)


def blend(recorded, generated):
    start = C.onset(recorded, -21)
    window = round(C.SR * 0.06)
    reference = rms(recorded[:window])
    layer = generated[:len(recorded) - start]
    mix = recorded.copy()
    mix[start:start + len(layer)] += layer * (0.68 * reference / rms(layer))
    mix *= reference / rms(mix[:window])
    # A smooth knee leaves the level-matched body alone and gives the MP3 headroom.
    amplitude = np.abs(mix)
    knee, ceiling = 0.46, 10 ** (-2 / 20)
    excess = np.maximum(0, amplitude - knee)
    return np.copysign(np.minimum(amplitude, knee) + excess / (1 + excess / (ceiling - knee)), mix)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('inputs', type=Path, help='Directory with raw C19 takes and provenance.json')
    inputs = parser.parse_args().inputs
    metadata = {row['name']: row for row in json.loads((inputs / 'provenance.json').read_text())}
    ledger = json.loads(CREDITS.read_text())
    original = {row['id']: row for row in ledger['sons'] if row['pack'] == 'armes'}
    credits = []
    for family, profiles in PLATFORMS.items():
        for take in (1, 2):
            raw = f'g_c19_{family}-{take}'
            generation = metadata[raw]
            generated = attack(C.load(inputs / (raw + '.mp3')))
            for profile in profiles:
                base = f'g_{profile}_pov-{take}'
                name = f'g_c19_{profile}_pov-{take}'
                recorded = C.load(CREDITS.parent / 'armes' / (base + '.mp3'))
                C.save_master(PACK, name, blend(recorded, generated))
                credits.append({
                    'id': name, 'pack': PACK, 'source': 'elevenlabs-c19',
                    'fichier': generation['id'],
                    'detail': (
                        f'{raw}: {generation["prompt"]} '
                        f'Generated by ElevenLabs Sound Effects v2 at {generation["credits"]:.3f} credits '
                        f'(generation shared across profiles in this family). '
                        f'Trimmed and faded mono attack, mixed into CC0 {base} '
                        f'({original[base]["source"]}, {original[base]["fichier"]}).'
                    ),
                })
    encode_pack(PACK, garder=True)
    ledger['sources']['elevenlabs-c19'] = {
        'nom': 'ElevenLabs Sound Effects v2 and CC0 Free Firearm Sound Library',
        'auteur': 'ElevenLabs generations for Escape From Claudov, layered into its credited FFSL recordings',
        'licence': 'ElevenLabs generated-output terms for the attack layer. CC0 1.0 for the base recording.',
        'url': 'https://elevenlabs.io/sound-effects',
        'preuve': 'Owner approved ElevenLabs use for C19 on 28 November 2026. Each entry records the generated take and the credited CC0 recording.',
    }
    ledger['sources'] = dict(sorted(ledger['sources'].items()))
    ledger['sons'] = [row for row in ledger['sons'] if row['pack'] != PACK] + sorted(credits, key=lambda row: row['id'])
    CREDITS.write_text(json.dumps(ledger, ensure_ascii=False, indent=1) + '\n')


if __name__ == '__main__':
    main()
